def test_required_server_defaults_have_expected_semantics(db_session: Session) -> None:
    transaction_timestamp = db_session.execute(text("SELECT transaction_timestamp()")).scalar_one()
    db_session.execute(text("INSERT INTO boards (id, name, kind) VALUES (2294, 'warrior', 'job')"))
    post_defaults = db_session.execute(
        text(
            "INSERT INTO posts "
            "(board_id, post_id, analysis_unit, title, published_at, source_url) "
            "VALUES (2294, 457159, 'hero', 'title', now(), 'https://example.invalid/457159') "
            "RETURNING is_notice, is_ad, last_seen_at"
        )
    ).one()
    snapshot_defaults = db_session.execute(
        text(
            "INSERT INTO post_metric_snapshots "
            "(board_id, post_id, observed_at_slot_kst, views, recommendations, comments, "
            "config_version) "
            "VALUES (2294, 457159, now(), 1, 2, 3, repeat('a', 64)) "
            "RETURNING observed_at_actual"
        )
    ).one()
    collection_defaults = db_session.execute(
        text(
            "INSERT INTO collection_runs "
            "(id, job_type, scheduled_at_slot_kst, status, config_version, started_at) "
            "VALUES (:id, 'metadata', now(), 'running', repeat('b', 64), now()) "
            "RETURNING diagnostics"
        ),
        {"id": uuid4()},
    ).one()
    work_defaults = db_session.execute(
        text(
            "INSERT INTO work_items (task_key, kind, state, available_at) "
            "VALUES ('all-defaults:v1', 'detail_fetch', 'pending', now()) "
            "RETURNING id, priority, payload, attempts, created_at, updated_at"
        )
    ).one()

    assert post_defaults.is_notice is False
    assert post_defaults.is_ad is False
    assert post_defaults.last_seen_at == transaction_timestamp
    assert snapshot_defaults.observed_at_actual == transaction_timestamp
    assert collection_defaults.diagnostics == {}
    assert work_defaults.id > 0
    assert work_defaults.priority == 100
    assert work_defaults.payload == {}
    assert work_defaults.attempts == 0
    assert work_defaults.created_at == transaction_timestamp
    assert work_defaults.updated_at == transaction_timestamp


