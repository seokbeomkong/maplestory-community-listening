def column_type_identity(column_type: object) -> tuple[str, int | None]:
    if isinstance(column_type, JSONB):
        return ("jsonb", None)
    if isinstance(column_type, PostgreSQLUUID):
        return ("uuid", None)
    if isinstance(column_type, DateTime):
        return ("timestamptz" if column_type.timezone else "timestamp", None)
    if isinstance(column_type, Boolean):
        return ("boolean", None)
    if isinstance(column_type, CHAR):
        return ("char", column_type.length)
    if isinstance(column_type, BigInteger):
        return ("bigint", None)
    if isinstance(column_type, SmallInteger):
        return ("smallint", None)
    if isinstance(column_type, Integer):
        return ("integer", None)
    if isinstance(column_type, Text):
        return ("text", None)
    raise AssertionError(f"unexpected reflected column type: {type(column_type).__name__}")


def test_core_table_identities_and_default_partition_exist(db_engine: Engine) -> None:
    table_names = set(inspect(db_engine).get_table_names())

    assert CORE_TABLES <= table_names
    with db_engine.connect() as connection:
        partition_bound = connection.execute(
            text(
                "SELECT pg_get_expr(child.relpartbound, child.oid) "
                "FROM pg_class AS child "
                "JOIN pg_namespace AS namespace ON namespace.oid = child.relnamespace "
                "WHERE namespace.nspname = current_schema() "
                "AND child.relname = 'post_metric_snapshots_default'"
            )
        ).scalar_one()
        partition_strategy, partition_columns = connection.execute(
            text(
                """
                SELECT partitioned.partstrat,
                       array_agg(attribute.attname ORDER BY partition_key.ordinality)
                FROM pg_catalog.pg_partitioned_table AS partitioned
                JOIN pg_catalog.pg_class AS parent ON parent.oid = partitioned.partrelid
                JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = parent.relnamespace
                CROSS JOIN LATERAL
                  unnest(partitioned.partattrs::smallint[]) WITH ORDINALITY
                  AS partition_key(attnum, ordinality)
                JOIN pg_catalog.pg_attribute AS attribute
                  ON attribute.attrelid = parent.oid
                 AND attribute.attnum = partition_key.attnum
                WHERE namespace.nspname = 'public'
                  AND parent.relname = 'post_metric_snapshots'
                GROUP BY partitioned.partstrat
                """
            )
        ).one()
    assert partition_bound == "DEFAULT"
    assert partition_strategy == "r"
    assert tuple(partition_columns) == ("observed_at_slot_kst",)


def test_catalog_column_types_and_nullability_match_exact_contract(db_engine: Engine) -> None:
    inspector = inspect(db_engine)

    for table_name, expected_columns in COLUMN_CONTRACTS.items():
        reflected_columns = {
            column["name"]: (column_type_identity(column["type"]), column["nullable"])
            for column in inspector.get_columns(table_name)
        }
        assert reflected_columns == expected_columns


def test_catalog_primary_foreign_and_unique_keys_match_exact_contract(
    db_engine: Engine,
) -> None:
    inspector = inspect(db_engine)

    for table_name in PRIMARY_KEY_CONTRACTS:
        primary_key = tuple(inspector.get_pk_constraint(table_name)["constrained_columns"])
        foreign_keys = {
            (
                tuple(foreign_key["constrained_columns"]),
                foreign_key["referred_table"],
                tuple(foreign_key["referred_columns"]),
            )
            for foreign_key in inspector.get_foreign_keys(table_name)
        }
        unique_keys = {
            tuple(unique_key["column_names"])
            for unique_key in inspector.get_unique_constraints(table_name)
        }

        assert primary_key == PRIMARY_KEY_CONTRACTS[table_name]
        assert foreign_keys == FOREIGN_KEY_CONTRACTS[table_name]
        assert unique_keys == UNIQUE_KEY_CONTRACTS[table_name]


